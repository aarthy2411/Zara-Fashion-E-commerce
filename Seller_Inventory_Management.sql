SELECT
    S.SELLER_ID,
    S.SELLER_NAME,
    S.CONTACT_NO,
    S.EMAIL,
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    I.INVENTORY_ID,
    I.STOCK_QUANTITY,
    I.STOCK_STATUS
FROM SELLER S
JOIN PRODUCT P
    ON P.SELLER_ID = S.SELLER_ID
JOIN INVENTORY I
    ON I.PRODUCT_ID = P.PRODUCT_ID
   AND I.SELLER_ID = S.SELLER_ID
ORDER BY S.SELLER_ID, P.PRODUCT_ID;


SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    STOCK_QUANTITY,
    STOCK_STATUS
FROM PRODUCT P
JOIN INVENTORY I ON I.PRODUCT_ID = P.PRODUCT_ID
ORDER BY PRODUCT_ID;


SELECT
    S.SELLER_NAME,
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    I.STOCK_QUANTITY,
    CASE
        WHEN I.STOCK_QUANTITY > 0 THEN 'Available'
        ELSE 'Unavailable'
    END AS AVAILABILITY_STATUS
FROM SELLER S
JOIN PRODUCT P ON P.SELLER_ID = S.SELLER_ID
JOIN INVENTORY I
    ON I.PRODUCT_ID = P.PRODUCT_ID
   AND I.SELLER_ID = S.SELLER_ID
ORDER BY P.PRODUCT_ID;


SELECT
    STOCK_STATUS,
    COUNT(*) AS TOTAL_PRODUCTS
FROM INVENTORY
GROUP BY STOCK_STATUS
ORDER BY STOCK_STATUS;


