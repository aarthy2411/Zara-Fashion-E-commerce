

CREATE TABLE SELLER (
    SELLER_ID   NUMBER(5)       PRIMARY KEY,
    SELLER_NAME VARCHAR2(100)   NOT NULL,
    CONTACT_NO  VARCHAR2(15),
    EMAIL       VARCHAR2(100)
);


CREATE TABLE PRODUCT (
    PRODUCT_ID   NUMBER(5)       PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(100)   NOT NULL,
    SELLER_ID    NUMBER(5)       NOT NULL,
    CONSTRAINT FK_PRODUCT_SELLER
        FOREIGN KEY (SELLER_ID) REFERENCES SELLER(SELLER_ID)
);


CREATE TABLE INVENTORY (
    INVENTORY_ID   NUMBER(5)      PRIMARY KEY,
    SELLER_ID      NUMBER(5)      NOT NULL,
    PRODUCT_ID     NUMBER(5)      NOT NULL,
    STOCK_QUANTITY NUMBER(10)     DEFAULT 0 NOT NULL,
    STOCK_STATUS   VARCHAR2(20)   NOT NULL,
    CONSTRAINT FK_INVENTORY_SELLER
        FOREIGN KEY (SELLER_ID) REFERENCES SELLER(SELLER_ID),
    CONSTRAINT FK_INVENTORY_PRODUCT
        FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID),
    CONSTRAINT CK_INVENTORY_QUANTITY
        CHECK (STOCK_QUANTITY >= 0),
    CONSTRAINT CK_INVENTORY_STATUS
        CHECK (STOCK_STATUS IN ('Available', 'Unavailable'))
);


